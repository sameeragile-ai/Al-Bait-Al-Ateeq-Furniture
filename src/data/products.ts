// Helper to get category details
export function getCategoryById(categoryId: string): CategoryInfo | undefined {
  return CATEGORIES.find((cat) => cat.id === categoryId);
}

// Helper to get product by slug or id
export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug || p.id === slug);
}

// Helper to get related products
export function getRelatedProducts(productId: string, category: string, limit = 4): Product[] {
  return PRODUCTS.filter((p) => p.id !== productId && p.category === category).slice(0, limit);
}
